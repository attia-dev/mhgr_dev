<h3>تمهيد</h3>
<p>حيث إن محجر منصة إلكترونية سعودية للمنتجات الفاخرة تعمل كنظام سوق إلكتروني يربط العملاء بالشركاء ويقدم بحسب الخدمة أدوات تقنية وتشغيلية لإدارة العرض والطلب والدفع والتوثيق والتسليم والاستلام والتسوية والشكاوى؛ وحيث يرغب الشريك التجاري في استخدام المنصة لعرض منتجاته للبيع و/أو التأجير؛ فقد اتفق الطرفان على أن تكون هذه الاتفاقية هي الاتفاقية الرئيسية المنظمة للعلاقة بينهما، وأن تسري على كل خدمة فقط عند تفعيل ملحقها الخاص.</p>

<h3>المادة (1): التعريفات</h3>
<p>لأغراض هذه الاتفاقية: «محجر» الجهة النظامية المشغلة للمنصة؛ «المنصة» الموقع أو التطبيق أو الواجهات الرقمية لمحجر؛ «الشريك» المؤسسة أو الشركة أو المتجر أو المنشأة المتعاقدة؛ «المنتج» السلعة المدرجة؛ «العميل» المستخدم النهائي؛ «عملية البيع» شراء منتج عبر المنصة؛ «عملية التأجير» تمكين مستأجر من حيازة المنتج مؤقتًا مقابل عوض؛ «ملحق الخدمة» الملحق الخاص بالبيع أو التأجير؛ «الجدول التجاري» جدول العمولات والرسوم والتسويات؛ «ملف المنتج» السجل الرقمي للمنتج؛ «تقرير الحالة» التقرير الذي يوثق حالة المنتج قبل التسليم وعند الإرجاع عند التأجير؛ «نقطة التسليم» الموقع أو الجهة المعتمدة ضمن إجراءات محجر؛ «التسوية» تحويل صافي المبالغ المستحقة للشريك بعد تحقق شروطها؛ «مستندات العملية» جميع السجلات والتقارير والموافقات المتعلقة بالعملية.</p>

<h3>المادة (2): موضوع الاتفاقية ونطاقها</h3>
<p>تنظم هذه الاتفاقية العلاقة العامة بين محجر والشريك فيما يتعلق بإدراج المنتجات وإدارة الحساب والبيانات والملكية والأصالة والعمولات والتسويات والخصوصية والسرية والمسؤولية والسجلات الإلكترونية. وتطبق الأحكام الخاصة بالبيع أو التأجير فقط عند تفعيل الملحق الخاص بالخدمة.</p>
<p>يعد الجدول التجاري وأي ملحق خدمة مفعّل جزءًا مكملًا لهذه الاتفاقية.</p>

<h3>المادة (3): الخدمات المفعلة</h3>
<p>تحدد الخدمات المفعلة في الجدول التجاري أو سجل التفعيل الإلكتروني. ويجوز أن تكون: التأجير فقط، أو البيع فقط، أو كلتا الخدمتين. ولا يترتب على تفعيل خدمة حق تلقائي في تفعيل الخدمة الأخرى.</p>

<h3>المادة (4): طبيعة العلاقة ودور محجر</h3>
<p>محجر منصة إلكترونية ووسيط تقني وتشغيلي، ولا تنتقل إليها ملكية المنتجات لمجرد الإدراج أو الحيازة المؤقتة للفحص أو التسليم. ويحدد دور محجر ومسؤولياتها بحسب الخدمة والعملية الفعلية وما تتولاه من أعمال.</p>
<p>لا تنشئ الاتفاقية شراكة قانونية أو علاقة عمل أو وكالة عامة بين الطرفين. ولا يعد الشريك ممثلًا لمحجر، ولا تعد محجر ممثلة للشريك، إلا في حدود تفويض صريح ومحدد إن وجد.</p>

<h3>المادة (5): بيانات الشريك والتفويض</h3>
<p>يقر الشريك بصحة بياناته النظامية وبيانات ممثله المفوض وسريان السجل والتراخيص اللازمة لنشاطه، ويلتزم بتحديثها فور حدوث تغيير جوهري.</p>
<p>لا يجوز لأي موظف أو ممثل غير مفوض إبرام التزامات باسم الشريك عبر المنصة خارج حدود صلاحياته المسجلة.</p>

<h3>المادة (6): الالتزام بالأنظمة والتراخيص</h3>
<p>يلتزم كل طرف بالأنظمة واللوائح التي تنطبق على دوره، وعلى الشريك المحافظة على التراخيص والتسجيلات والالتزامات الضريبية والتجارية اللازمة لممارسة نشاطه، ولا يعد قبول حسابه في المنصة إعفاءً من أي التزام نظامي مستقل.</p>

<h3>المادة (7): ملكية المنتجات والحق في التصرف</h3>
<p>يقر الشريك بأنه يملك المنتجات المدرجة أو يملك الحق النظامي في بيعها أو تأجيرها بحسب الخدمة، وأنه لا يعلم بوجود رهن أو حجز أو مطالبة أو حق للغير يمنع التصرف فيها.</p>
<p>يجوز لمحجر طلب ما يلزم بصورة معقولة لإثبات الملكية أو مصدر المنتج أو حق التصرف، وتعليق المنتج أو العملية عند وجود مؤشر جدي على نزاع في الملكية.</p>

<h3>المادة (8): الأصالة ومكافحة التقليد</h3>
<p>يلتزم الشريك بعدم عرض منتج مقلد على أنه أصلي، وبصحة أي وصف أو شهادة أو ادعاء يتعلق بالأصالة. ويجوز لمحجر طلب مستندات أو فحص متخصص قبل أو بعد الإدراج عند وجود حاجة تشغيلية أو مؤشر مخاطر.</p>
<p>لا يشكل قبول الإدراج شهادة مطلقة من محجر بأصالة المنتج ما لم تقدم محجر خدمة تحقق مستقلة وصريحة بهذه الصفة.</p>

<h3>المادة (9): ملف المنتج والمعلومات</h3>
<p>يلتزم الشريك بتقديم وصف دقيق وحقيقي للمنتج، بما في ذلك الفئة والماركة والموديل والحالة والعيوب الجوهرية المعروفة والملحقات والرقم المرجعي أو التسلسلي عند الحاجة والصور المناسبة وأي معلومات لازمة لاتخاذ قرار واعٍ.</p>
<p>يجوز لمحجر إخفاء كامل الرقم التسلسلي والبيانات غير اللازمة عن العرض العام مع الاحتفاظ بها داخليًا لأغراض التحقق وإدارة المخاطر.</p>

<h3>المادة (10): المخزون والتوفر</h3>
<p>يلتزم الشريك بإبقاء حالة التوفر محدثة، وعدم تأكيد طلب على منتج غير متاح. ويجوز لمحجر تعليق المنتج عند تكرار إلغاءات ناتجة عن عدم دقة المخزون.</p>

<h3>المادة (11): الأسعار والشفافية</h3>
<p>يحدد سعر البيع أو التأجير وآلية تعديله وفق ملحق الخدمة والجدول التجاري. ويجب ألا يتغير السعر أو الرسوم المتعلقة بعملية مؤكدة بأثر رجعي إلا بموافقة لازمة أو سبب نظامي.</p>
<p>تظهر للمستخدم المعلومات الجوهرية المتعلقة بالسعر والرسوم والضرائب والتوصيل أو التنفيذ قبل إتمام العملية بحسب ما ينطبق.</p>

<h3>المادة (12): العمولات والرسوم</h3>
<p>تستحق محجر العمولة والرسوم المحددة في الجدول التجاري الساري وقت العملية. ولا تستحق رسوم غير مفصح عنها للشريك وفق العلاقة المتفق عليها.</p>
<p>أي تغيير على العمولة أو الرسوم لا يسري على عملية مؤكدة قبل نفاذ التغيير إلا إذا اتفق الطرفان صراحة أو كان التغيير مفروضًا نظامًا.</p>

<h3>المادة (13): المدفوعات والتحصيل</h3>
<p>تتم المدفوعات من خلال وسائل الدفع المعتمدة لدى محجر أو مقدم خدمات الدفع ذي الصلة. ولا تفترض هذه الاتفاقية أن محجر تحتفظ بأموال العملاء أو تقدم خدمة حساب ضمان ما لم ينص ترتيب مستقل وصريح على ذلك.</p>
<p>يلتزم الشريك بعدم مطالبة العميل بتحويل قيمة عملية نشأت عبر محجر إلى حساب خارج المسار المعتمد بقصد تجاوز المنصة أو إجراءات الحماية.</p>

<h3>المادة (14): التسويات المالية</h3>
<p>تسوى مستحقات الشريك وفق الجدول التجاري وبعد تحقق شروط الاستحقاق الخاصة بالخدمة. ويجوز تعليق الجزء المرتبط مباشرة بنزاع أو استرجاع أو اعتراض دفع إلى حين تحديد أثره، دون حجز مبالغ لا علاقة لها بالمسألة دون مبرر.</p>
<p>يجوز إجراء المقاصة أو الاسترداد من تسويات لاحقة عند ثبوت استحقاق مبلغ لمحجر أو عميل نتيجة استرجاع أو رد صحيح أو خطأ في تسوية سابقة، بشرط وجود أساس تعاقدي أو نظامي واضح وسجل للمبلغ وسببه.</p>

<h3>المادة (15): الفواتير والضرائب</h3>
<p>يتحمل كل طرف التزاماته الضريبية والفوترة التي تقع عليه بحسب صفته ودوره. وعندما يكون الشريك هو المورد أو البائع النظامي، يبقى مسؤولًا عن إصدار الفاتورة أو المستند الضريبي المطلوب ما لم يوجد ترتيب نظامي منفصل يسمح لمحجر بإصداره نيابة عنه.</p>
<p>لا تحدد هذه الاتفاقية نسبة ضريبية غير مقررة، وتطبق الضرائب وفق الأنظمة السارية وقت العملية.</p>

<h3>المادة (16): التزامات محجر العامة</h3>
<p>تلتزم محجر بتشغيل المنصة وإدارة العمليات ضمن نطاق دورها المتفق عليه، وحفظ السجلات التشغيلية الأساسية، وإظهار المعلومات التي يجب الإفصاح عنها، وتطبيق إجراءات معقولة للشكاوى والنزاعات، والاستعانة بمقدمي خدمات عند الحاجة مع مراعاة الالتزامات النظامية ذات الصلة.</p>

<h3>المادة (17): التزامات الشريك العامة</h3>
<p>يلتزم الشريك بتنفيذ الطلبات المؤكدة، وتجهيز المنتج الصحيح بالحالة والملحقات المتفق عليها، والتعاون في الفحص والتسليم والاسترجاع والنزاعات، والرد على طلبات محجر خلال المدد التشغيلية المحددة في الجدول أو النظام.</p>

<h3>المادة (18): نقاط التسليم والاستلام</h3>
<p>يجوز اعتماد متجر الشريك أو موقع آخر كنقطة تسليم واستلام إذا وافقت محجر على ذلك. وفي هذه الحالة يلتزم الشريك وموظفوه بإجراءات محجر، وعدم تسليم أو استلام المنتج خارج حالة النظام المعتمدة، وتوثيق الموظف والوقت والموقع والمنتج وفق الآلية المقررة.</p>

<h3>المادة (19): حماية بيانات العملاء</h3>
<p>لا يجوز للشريك استخدام بيانات العملاء إلا بالقدر اللازم لتنفيذ العملية أو الامتثال لالتزام نظامي أو وفق مسوغ آخر مشروع. ولا يجوز استخدام بيانات عميل محجر للتسويق المستقل أو مشاركتها مع طرف غير لازم دون مسوغ مناسب.</p>
<p>يلتزم الطرفان بتطبيق الضوابط الفنية والتنظيمية المناسبة على البيانات التي تقع تحت سيطرتهما، وتحدد أدوارهما في معالجة البيانات وفق طبيعة المعالجة الفعلية وسياسة الخصوصية والترتيبات ذات الصلة.</p>

<h3>المادة (20): السرية</h3>
<p>يحافظ كل طرف على سرية المعلومات غير العامة التي يحصل عليها بسبب العلاقة، بما في ذلك المعلومات التجارية والمالية والتقنية وبيانات العمليات، ولا يفصح عنها إلا للموظفين أو المستشارين أو مقدمي الخدمات الذين يحتاجون إليها أو عند وجود التزام نظامي.</p>

<h3>المادة (21): الملكية الفكرية والمحتوى</h3>
<p>يبقى كل طرف مالكًا لعلاماته وحقوقه. ويمنح الشريك محجر ترخيصًا غير حصري ومحدودًا بمدة العلاقة لاستخدام الاسم التجاري والعلامة وصور المنتجات والأوصاف بالقدر اللازم لعرض المنتجات وتسويقها وتشغيل الخدمة.</p>
<p>يقر الشريك بأن المحتوى الذي يقدمه لا ينتهك حقوق الغير، ويزيل أو يصحح أي محتوى عند ثبوت عدم صحة الحق في استخدامه.</p>

<h3>المادة (22): التقييمات والمحتوى المتعلق بالتجربة</h3>
<p>يجوز للمنصة تمكين العملاء من تقييم تجربتهم وفق قواعدها. ويحظر إنشاء تقييمات وهمية أو التلاعب بها أو الضغط على العملاء مقابل تقييم مضلل.</p>

<h3>المادة (23): منع التحايل خارج المنصة</h3>
<p>إذا تعرف الشريك على عميل أو طلب بسبب محجر، فلا يجوز له تحويل نفس العملية أو امتدادها المباشر المتفق عليه خارج المنصة بقصد تجنب العمولة أو إجراءات الحماية. ولا يفسر هذا البند على أنه حظر عام ودائم لكل علاقة مستقلة لا تنشأ عن التحايل على عملية محجر.</p>

<h3>المادة (24): مكافحة الاحتيال والاستخدام غير المشروع</h3>
<p>يجوز لمحجر تعليق طلب أو منتج أو حساب عند وجود مؤشرات جدية على احتيال أو تزوير أو منتج مقلد أو ملكية محل نزاع أو إساءة استخدام، على أن يكون الإجراء متناسبًا مع الخطر وبالقدر اللازم للتحقق وحماية الأطراف.</p>

<h3>المادة (25): الشكاوى والنزاعات التشغيلية</h3>
<p>يتعاون الطرفان في معالجة الشكاوى وتقديم المعلومات والأدلة ذات الصلة. ولا يمثل قرار محجر التشغيلي الداخلي حكمًا قضائيًا نهائيًا، ولا يمنع أي طرف من ممارسة حقه لدى الجهات المختصة.</p>

<h3>المادة (26): السجلات والأدلة الإلكترونية</h3>
<p>يجوز لمحجر حفظ سجلات إلكترونية للاتفاقية وملحقاتها وتفعيل الخدمات والطلبات والموافقات والدفع والتسليم والاستلام والتقارير والمراسلات. وتستخدم هذه السجلات وفق الأنظمة ذات الصلة بالإثبات والمعاملات الإلكترونية دون اعتبارها دليلًا نهائيًا غير قابل للمناقشة.</p>

<h3>المادة (27): الاستعانة بمقدمي خدمات</h3>
<p>يجوز لمحجر الاستعانة بمقدمي خدمات الدفع أو التقنية أو الهوية أو النقل أو الفحص أو التخزين أو التواصل لتنفيذ الخدمة، دون أن يؤدي ذلك بذاته إلى تغيير توزيع المسؤوليات النظامية بين الأطراف. ويلتزم الشريك بالتعاون مع الإجراءات المعتمدة ذات الصلة.</p>

<h3>المادة (28): المسؤولية وتوزيع المخاطر</h3>
<p>يتحمل كل طرف المسؤولية عن إخلاله والتزاماته الواقعة ضمن نطاق سيطرته وفق الأنظمة وهذه الاتفاقية. ولا تتضمن الاتفاقية إعفاءً من مسؤولية لا يجوز نظامًا الإعفاء منها.</p>
<p>لا تضمن محجر للشريك تحقيق حد أدنى من المبيعات أو التأجيرات، ولا تضمن ملاءة أي عميل أو تحصيل كامل قيمة منتج مفقود أو غير معاد إلا إذا قدمت ضمانًا مستقلًا وصريحًا بشروطه.</p>

<h3>المادة (29): تعويض المطالبات الناشئة عن إخلال الشريك</h3>
<p>يتحمل الشريك ما يثبت نظامًا من أضرار أو مطالبات مباشرة نشأت عن مخالفته الجوهرية لالتزامات الملكية أو الأصالة أو حق التصرف أو انتهاك حقوق الغير أو تقديم معلومات مضللة، وذلك دون توسيع التعويض ليشمل مبالغ جزافية أو غير مثبتة.</p>

<h3>المادة (30): القوة القاهرة والظروف الخارجة عن السيطرة</h3>
<p>لا يعد الطرف مخلاً بقدر ما يتعذر عليه التنفيذ بسبب ظرف خارج عن سيطرته على النحو الذي تقره الأنظمة، ويلتزم بإشعار الطرف الآخر واتخاذ خطوات معقولة لتقليل الأثر واستئناف التنفيذ متى أمكن.</p>

<h3>المادة (31): مدة الاتفاقية</h3>
<p>تبدأ هذه الاتفاقية من تاريخ قبولها أو توقيعها وتستمر لمدة %Partner.AgreementTerm%، وتتجدد وفق %Partner.RenewalBasis% ما لم يتم إنهاؤها وفق أحكامها.</p>

<h3>المادة (32): التعليق والإنهاء</h3>
<p>يجوز لأي طرف إنهاء الاتفاقية بإشعار مدته %Partner.TerminationNoticeDays% يومًا/يوم عمل، مع مراعاة العمليات القائمة. ويجوز لمحجر التعليق الفوري عند وجود مخالفة جوهرية أو خطر احتيال أو منتج مقلد أو مسروق أو سبب نظامي يستدعي ذلك، مع تمكين المعالجة عند ملاءمتها.</p>

<h3>المادة (33): أثر الإنهاء</h3>
<p>لا يؤثر انتهاء الاتفاقية على الطلبات المؤكدة أو التسويات أو الاسترجاعات أو النزاعات أو الالتزامات التي نشأت قبل الإنهاء، وتبقى أحكام السرية والبيانات والملكية الفكرية والسجلات والمسؤوليات السابقة بالقدر اللازم.</p>

<h3>المادة (34): التعديل وإدارة الإصدارات</h3>
<p>يجوز تحديث الاتفاقية أو الملاحق للأسباب التشغيلية أو النظامية، ويظهر رقم الإصدار وتاريخ النفاذ. ولا تطبق التعديلات الجوهرية على عملية مؤكدة بأثر رجعي دون أساس نظامي أو قبول مناسب.</p>

<h3>المادة (35): الإشعارات</h3>
<p>ترسل الإشعارات إلى بيانات الاتصال المسجلة أو عبر المنصة أو البريد المعتمد. ويلتزم الشريك بتحديث بياناته، وتحدد الحالات التي تتطلب إشعارًا رسميًا خاصًا وفق النظام أو الاتفاق.</p>

<h3>المادة (36): أولوية المستندات</h3>
<p>عند التعارض، تكون الأولوية للأنظمة الإلزامية، ثم الشروط الخاصة بالعملية، ثم ملحق الخدمة المفعّل، ثم هذه الاتفاقية الرئيسية، ثم الجدول التجاري، ثم الإجراءات التشغيلية بالقدر الذي لا يتعارض مع ما سبق.</p>

<h3>المادة (37): التنازل والتحويل</h3>
<p>لا يجوز للشريك نقل هذه الاتفاقية أو حسابه أو التزاماته الجوهرية إلى طرف آخر دون موافقة محجر، ما لم يفرض النظام خلاف ذلك. ويجوز لمحجر إعادة تنظيم تنفيذ الخدمة عبر شركة تابعة أو مقدم خدمة دون نقل التزاماتها النظامية بصورة تضر بحقوق الطرف الآخر.</p>

<h3>المادة (38): القانون وتسوية النزاعات</h3>
<p>تخضع هذه الاتفاقية لأنظمة المملكة العربية السعودية. ويسعى الطرفان إلى تسوية النزاع وديًا خلال %Partner.AmicableSettlementDays% يوم عمل من اكتمال الإشعار بالنزاع، وإذا تعذر الحل تكون المنازعة من اختصاص الجهة القضائية المختصة في المملكة، ما لم يتفق الطرفان في وثيقة مستقلة صحيحة على وسيلة نظامية أخرى.</p>

<h3>المادة (39): القبول الإلكتروني</h3>
<p>يجوز إبرام هذه الاتفاقية وقبول ملاحقها إلكترونيًا وفق الأنظمة ذات الصلة. ويحفظ النظام معرف الطرف، واسم الوثيقة، ورقم الإصدار، وتاريخ ووقت القبول، والخدمات المفعلة، والمرجع التقني المرتبط بالقبول.</p>

