<h2>الملحق (ب): الشروط الخاصة بخدمة التأجير للشريك التجاري</h2>
<p>يسري هذا الملحق فقط إذا كانت خدمة التأجير مفعلة للشريك. ويكمل الاتفاقية الرئيسية ولا يستبدلها.</p>

<h3>المادة (1): نطاق خدمة التأجير</h3>
<p>يتيح الشريك منتجاته للتأجير عبر المنصة وفق المدد والأسعار والتوفر المبين في كل طلب، وتدير محجر العملية بحسب دورها التشغيلي والتقني.</p>

<h3>المادة (2): حدود قبول المنتجات</h3>
<p>يخضع قبول المنتج لسياسات المخاطر والفئة والحالة والقيمة. ويبلغ الحد التجريبي الحالي لقيمة القطعة المؤهلة للتأجير %Partner.RentalItemValueCap% ريال سعودي ما لم تعتمد محجر خلاف ذلك كتابة أو إلكترونيًا.</p>

<h3>المادة (3): أهلية المستأجر</h3>
<p>تدير محجر أهلية المستأجر وحدوده وفق إجراءات المخاطر المتاحة لها، ولا يمثل قبول المستأجر ضمانًا لوفائه أو ملاءته أو عدم تعرض المنتج لأي حادث.</p>

<h3>المادة (4): طلب التأجير والتأكيد</h3>
<p>لا يصبح الطلب جاهزًا للتسليم إلا بعد استكمال ما ينطبق من التوفر والموافقة والدفع والقبول التعاقدي والضمانات وتقرير الحالة. ولا يكفي الدفع وحده لإلزام الشريك بالتسليم إذا بقيت متطلبات جوهرية غير مكتملة.</p>

<h3>المادة (5): تجهيز المنتج</h3>
<p>يلتزم الشريك بتجهيز نفس المنتج المدرج وبالملحقات والحالة الموصوفة، وعدم الاستبدال إلا بعد تحديث العملية والحصول على الموافقات اللازمة.</p>

<h3>المادة (6): تقرير حالة القطعة</h3>
<p>يجب إنشاء تقرير حالة قبل التسليم يتضمن بحسب نوع المنتج الصور والفيديو والرقم المرجعي أو التسلسلي والملحقات والعيوب أو الخدوش السابقة وحالة الأجزاء الجوهرية. ويعد التقرير جزءًا مكملًا للعملية.</p>
<p>لا يجوز تعديل التقرير الأصلي بعد التسليم بطريقة تمحو النسخة السابقة؛ ويجب أن يسجل أي تصحيح لاحق مع أثره الزمني.</p>

<h3>المادة (7): التسليم وسلسلة الحيازة</h3>
<p>يتم التسليم من خلال النقطة أو الآلية المعتمدة، ويجوز استخدام رمز تحقق أو QR أو وسيلة إلكترونية أخرى. ويوثق النظام المنتج والطلب والوقت والمكان والموظف/الجهة وطريقة التحقق.</p>
<p>إذا كان متجر الشريك نقطة تسليم معتمدة، فلا يسلم المنتج قبل ظهور الحالة التشغيلية المصرح بها في النظام.</p>

<h3>المادة (8): مدة التأجير والتوفر</h3>
<p>تحدد مدة التأجير وموعد الإرجاع والسعر في ملخص الطلب. ولا يعد استمرار حيازة المستأجر بعد الموعد تمديدًا تلقائيًا، ويجب اعتماد أي تمديد عبر المنصة.</p>

<h3>المادة (9): الإرجاع والفحص</h3>
<p>عند الإرجاع ينشأ تقرير حالة جديد وتتم مقارنة المنتج والرقم التسلسلي والملحقات والحالة بالبيانات السابقة. وإذا ظهرت ملاحظة جديدة لا يغلق الطلب على أنه سليم قبل معالجة الحالة.</p>

<h3>المادة (10): الاستهلاك المعتاد والضرر</h3>
<p>لا يعد أثر الاستخدام المعتاد والمتناسب مع طبيعة المنتج ومدة التأجير ضررًا موجبًا للتعويض تلقائيًا. وتراجع أي مطالبة بضرر جديد بناءً على الأدلة والسبب وعلاقة الضرر بحيازة المستأجر.</p>

<h3>المادة (11): تقييم الضرر</h3>
<p>لا يكون تقدير الشريك منفردًا ملزمًا للمستأجر. ويجوز الاستناد إلى تقرير قبل/بعد والصور والفيديو وتكلفة الإصلاح المعقولة وتكلفة الجزء والانخفاض المثبت في القيمة أو قيمة الاستبدال عند تعذر الإصلاح، مع خبير عند الحاجة.</p>

<h3>المادة (12): الملحقات المفقودة</h3>
<p>لا تعتمد مطالبة بملحق مفقود ما لم يكن موثقًا ضمن مستندات التسليم، وتقدر الخسارة وفق تكلفة الاستبدال أو الأثر الاقتصادي المثبت.</p>

<h3>المادة (13): الفقد والسرقة</h3>
<p>عند الفقد أو السرقة تفتح حالة مراجعة وتجمع الأدلة والبلاغات عند الحاجة. ولا يؤدي وصف الواقعة بأنها سرقة إلى إعفاء أو إدانة تلقائية لأي طرف، وتحدد المسؤولية وفق الظروف والأدلة والأنظمة.</p>

<h3>المادة (14): التأخير وعدم الإرجاع</h3>
<p>عند تجاوز موعد الإرجاع دون تمديد معتمد، تسجل العملية متأخرة وتطبق إجراءات التواصل والتصعيد والرسوم المعلنة إن وجدت. وإذا استمر عدم الإرجاع يجوز تعليق العميل وتفعيل وسائل الحماية المتفق عليها واتخاذ الإجراءات النظامية.</p>
<p>لا تضمن محجر للشريك استرداد كامل قيمة المنتج أو تحصيلها إلا بموجب ضمان مستقل وصريح.</p>

<h3>المادة (15): الضمانات والسند لأمر</h3>
<p>يجوز لمحجر اشتراط ضمان مالي أو سند لأمر إلكتروني أو وسيلة حماية أخرى بحسب العملية وبما يتم الإفصاح عنه. ولا يمثل أي منها منفردًا ضمانًا مطلقًا للتحصيل أو إثباتًا تلقائيًا لكل قيمة مطالبة مستقبلية.</p>

<h3>المادة (16): الإلغاء</h3>
<p>تعالج الإلغاءات وفق مرحلة الطلب وسبب الإلغاء وحقوق العميل النظامية. ويلتزم الشريك بعدم إلغاء طلب مؤكد دون سبب مشروع، وتحدد آثار الإلغاء والرسوم في الجدول أو شروط العملية.</p>

<h3>المادة (17): تسوية عائد التأجير</h3>
<p>يستحق الشريك صافي عائد التأجير بعد تحقق شروط التسوية المبينة في الجدول التجاري، ويجوز تعليق الجزء المتنازع عليه إلى حين حسم أثر الضرر أو الاسترجاع أو الاعتراض.</p>

<h2>الملحق (ج): الشروط الخاصة بخدمة البيع والعمولة للشريك التجاري</h2>
<p>يسري هذا الملحق فقط إذا كانت خدمة البيع مفعلة للشريك. ويكمل الاتفاقية الرئيسية والجدول التجاري.</p>

<h3>المادة (1): نطاق البيع</h3>
<p>يعرض الشريك منتجاته للبيع عبر محجر وفق السعر والحالة والوصف والتوفر المعلن لكل منتج، وتدار عملية الشراء والتسليم والاسترجاع والتسوية وفق هذا الملحق.</p>

<h3>المادة (2): وصف المنتج وحالته</h3>
<p>يجب بيان ما إذا كان المنتج جديدًا أو مستعملًا أو مجددًا عند انطباق ذلك، والإفصاح عن العيوب الجوهرية المعروفة وآثار الاستخدام المؤثرة على قرار المشتري.</p>

<h3>المادة (3): السعر والطلب</h3>
