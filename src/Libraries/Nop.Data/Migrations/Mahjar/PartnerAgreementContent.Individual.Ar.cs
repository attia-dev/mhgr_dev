<h2>الملحق (ب): الشروط الخاصة بتأجير منتجات الشريك الفرد</h2>
<p>يسري هذا الملحق عند تفعيل خدمة التأجير للشريك الفرد.</p>

<h3>المادة (1): المنتجات المؤهلة وحد القيمة</h3>
<p>تخضع القطعة لمراجعة الفئة والحالة والملكية والمخاطر. ويبلغ الحد التجريبي الحالي لقيمة القطعة %Partner.RentalItemValueCap% ريال سعودي ما لم تعتمد محجر استثناءً.</p>

<h3>المادة (2): الطلب وموافقة الشريك</h3>
<p>عند ورود طلب يجوز للشريك قبول الطلب أو رفضه وفق حالة التوفر قبل تأكيد العملية. وبعد التأكيد يلتزم بتجهيز القطعة وعدم التعامل خارج المنصة بشأن نفس الطلب.</p>

<h3>المادة (3): أهلية المستأجر</h3>
<p>تتولى محجر إدارة أهلية المستأجر وفق إجراءاتها المتاحة. ولا يمثل قبول المستأجر ضمانًا لعدم حدوث تأخير أو ضرر أو فقد أو عدم إرجاع.</p>

<h3>المادة (4): الضمانات</h3>
<p>يجوز أن تتطلب العملية ضمانًا ماليًا أو سندًا لأمر أو وسيلة حماية أخرى تظهر في شروط العملية. ولا يعد وجود وسيلة واحدة ضمانًا مطلقًا للتحصيل أو استرداد المنتج.</p>

<h3>المادة (5): تسليم القطعة إلى نقطة محجر</h3>
<p>يلتزم الشريك بتسليم نفس القطعة المسجلة، ويفضل في عمليات الأفراد أن يتم التسليم عبر نقطة أو جهة معتمدة بدل التسليم المباشر غير الموثق بين الطرفين.</p>

<h3>المادة (6): تقرير حالة القطعة</h3>
<p>يتم توثيق الحالة قبل انتقال الحيازة للمستأجر بالصور والفيديو والرقم التسلسلي والملحقات والخدوش السابقة وغيرها بحسب نوع المنتج. ويعد التقرير جزءًا من العملية.</p>

<h3>المادة (7): سلسلة الحيازة</h3>
<p>يوثق النظام انتقال الحيازة بين الشريك ونقطة التسليم والمستأجر وعند الإرجاع، بحسب النموذج التشغيلي. ولا يتحمل الشريك أو المستأجر تلقائيًا فترة حيازة لم تكن لديه فعليًا وفق السجل والأدلة.</p>

<h3>المادة (8): الإرجاع</h3>
<p>يتم الإرجاع بالطريقة المعتمدة وإعادة الفحص والمقارنة قبل إغلاق العملية.</p>

<h3>المادة (9): الاستهلاك والضرر</h3>
<p>لا يعد الاستخدام المعتاد المتناسب مع طبيعة المنتج ومدة التأجير ضررًا قابلًا للتعويض تلقائيًا. وعند وجود اختلاف جديد تفتح مراجعة ضرر ويستند التقييم إلى الأدلة وليس إلى تقدير الشريك وحده.</p>

<h3>المادة (10): تقدير المطالبة</h3>
<p>يجوز احتساب المطالبة على أساس الإصلاح المعقول أو الجزء المتضرر أو الانخفاض المثبت في القيمة أو الاستبدال عند تعذر الإصلاح، مع الاستعانة بجهة فنية عند الحاجة.</p>

<h3>المادة (11): الفقد والسرقة وعدم الإرجاع</h3>
<p>تدار الحالات عبر ملف أدلة وتصعيد، ولا تضمن محجر للشريك كامل قيمة المنتج ما لم يوجد ضمان مستقل. ويلتزم الشريك بتقديم ما يثبت الملكية والقيمة والمعلومات اللازمة للمطالبة.</p>

<h3>المادة (12): التأخير</h3>
<p>تطبق على المستأجر إجراءات ورسوم التأخير المعلنة إن وجدت، ولا يعد التأخير موافقة تلقائية على تمديد التأجير.</p>

<h3>المادة (13): التسوية</h3>
<p>يسوى صافي عائد التأجير للشريك وفق الجدول التجاري وشروط إغلاق العملية. ويجوز تعليق الجزء المرتبط بمطالبة قائمة إلى حين معالجتها.</p>

<h2>الملحق (ج): الشروط الخاصة ببيع منتجات الشريك الفرد والعمولة</h2>
<p>يسري هذا الملحق عند تفعيل خدمة البيع للشريك الفرد.</p>

<h3>المادة (1): الملكية والبيع</h3>
<p>يؤكد الشريك أنه يملك القطعة وله حق بيعها، وأنه لا يعرض منتجًا مسروقًا أو مفقودًا أو مقلدًا أو محل حق يمنع التصرف.</p>

<h3>المادة (2): حالة المنتج</h3>
<p>يجب وصف المنتج المستعمل بدقة والإفصاح عن العيوب والإصلاحات والآثار الجوهرية المعروفة، وتكون الصور حديثة وتمثل القطعة المعروضة قدر الإمكان.</p>

<h3>المادة (3): السعر والعمولة</h3>
<p>يحدد سعر البيع في ملف المنتج أو ملخص العملية، وتخصم عمولة محجر والرسوم المحددة في الجدول التجاري عند تحقق استحقاقها.</p>

<h3>المادة (4): الطلب والتوفر</h3>
<p>لا يعتبر المنتج مباعًا نهائيًا لمجرد اهتمام العميل أو إنشاء الطلب قبل استكمال الدفع وأي فحص أو متطلبات لازمة. ويلتزم الشريك بعدم التصرف في المنتج خارج المنصة بعد تأكيد الطلب إلا بإلغاء نظامي.</p>

<h3>المادة (5): الفحص والأصالة</h3>
<p>يجوز طلب فحص للملكية أو الأصالة أو الحالة قبل التسليم. وإذا ظهرت مشكلة جوهرية يجوز تعليق أو إلغاء العملية وفق نتيجتها.</p>

<h3>المادة (6): التسليم</h3>
<p>يتم تسليم المنتج عبر الطريقة المعتمدة وتوثق الملحقات والهوية الداخلية للقطعة عند الحاجة.</p>

<h3>المادة (7): عدم المطابقة والاسترجاع</h3>
<p>تطبق حقوق المشتري النظامية والشروط المعلنة للعملية. وإذا كان المنتج غير مطابق جوهريًا أو ظهرت مشكلة في الأصالة أو الملكية، يتعاون الشريك في الإرجاع ورد المبالغ المستحقة بحسب الحالة.</p>

<h3>المادة (8): فحص المرتجع</h3>
<p>يجوز فحص المنتج المرتجع وتوثيق حالته خلال %Partner.ReturnInspectionDays% يوم عمل، ولا يحمل المشتري أثرًا لم يثبت أنه نشأ بعد التسليم أو بسبب يوجب مسؤوليته.</p>

<h3>المادة (9): التسوية والاسترجاع بعد التسوية</h3>
<p>تسوى مستحقات الشريك وفق الجدول التجاري. وإذا تم استرجاع العملية بصورة صحيحة بعد التسوية، يجوز معالجة المبلغ المستحق في تسوية لاحقة أو بطلب سداد موثق بحسب سبب الاسترجاع.</p>

<h3>المادة (10): الالتزامات النظامية عند تكرار البيع</h3>
<p>إذا تحول نشاط الشريك إلى ممارسة تجارية أو مهنية تستلزم تسجيلًا أو التزامات إضافية، يلتزم باتخاذ الإجراءات اللازمة ولا يستمر في تقديم نفسه كبيع فردي عرضي إذا لم يعد ذلك يعكس الواقع.</p>

