<h3>تمهيد</h3>
<p>حيث إن محجر منصة إلكترونية سعودية للمنتجات الفاخرة تتيح للأفراد عرض المنتجات التي يملكونها للبيع و/أو التأجير وفق ضوابط المنصة؛ وحيث يرغب الشريك الفرد في الاستفادة من المنصة للتصرف في منتجات يملكها بصورة مشروعة؛ فقد اتفق الطرفان على أن تكون هذه الاتفاقية هي الاتفاقية الرئيسية المنظمة للعلاقة، وأن تسري أحكام كل خدمة فقط عند تفعيل ملحقها الخاص.</p>

<h3>المادة (1): التعريفات</h3>
<p>لأغراض هذه الاتفاقية: «محجر» الجهة المشغلة للمنصة؛ «الشريك الفرد» الشخص الطبيعي صاحب الحساب والمنتج؛ «المنتج» القطعة المدرجة؛ «العميل» المشتري أو المستأجر بحسب العملية؛ «ملحق الخدمة» ملحق البيع أو التأجير؛ «ملف المنتج» السجل الرقمي للقطعة؛ «تقرير الحالة» توثيق حالة المنتج لأغراض التأجير؛ «التسوية» تحويل صافي المبالغ المستحقة للشريك؛ «مستندات العملية» جميع السجلات والموافقات والتقارير الخاصة بالطلب.</p>

<h3>المادة (2): موضوع الاتفاقية ونطاقها</h3>
<p>تنظم هذه الاتفاقية العلاقة العامة بين محجر والشريك الفرد فيما يتعلق بالحساب، والتحقق، وملكية المنتجات وأصالتها، وإدراجها، والرسوم والتسويات، والخصوصية، والمسؤولية، والسجلات الإلكترونية. ويطبق ملحق البيع أو التأجير فقط عند تفعيل الخدمة ذات الصلة.</p>

<h3>المادة (3): الخدمات المفعلة</h3>
<p>تحدد الخدمة في سجل التفعيل: %Partner.ActivatedServices%. ويمكن تفعيل أو إيقاف إحدى الخدمتين دون إنهاء الاتفاقية الرئيسية ما لم تتطلب الظروف خلاف ذلك.</p>

<h3>المادة (4): طبيعة دور محجر</h3>
<p>محجر منصة ووسيط تقني وتشغيلي، ولا تصبح مالكة للمنتج لمجرد الإدراج أو الحيازة المؤقتة لأغراض الفحص أو التسليم. وقد تتولى عبرها أو عبر مقدمي خدمات التحقق والدفع والفحص والتسليم والاستلام والتوثيق والنزاعات والتسويات.</p>
<p>لا تضمن محجر نجاح بيع أو تأجير المنتج، ولا تضمن ملاءة العميل أو تحصيل كامل قيمة منتج مفقود أو غير معاد إلا بضمان مستقل وصريح.</p>

<h3>المادة (5): الأهلية والتحقق</h3>
<p>يقر الشريك الفرد بأنه ذو أهلية نظامية وأن بياناته صحيحة. ويجوز لمحجر التحقق من هويته من خلال الوسائل المعتمدة. ولا يعني اجتياز التحقق قبول كل منتج أو كل عملية تلقائيًا.</p>

<h3>المادة (6): طبيعة نشاط الفرد والالتزامات النظامية</h3>
<p>يستخدم الشريك الفرد المنصة لبيع أو تأجير منتجات يملكها أو يملك حق التصرف فيها. وإذا تحول نشاطه من حيث الاستمرارية أو الحجم أو التنظيم إلى نشاط يتطلب تسجيلًا أو ترخيصًا أو التزامًا إضافيًا، فيلتزم باستيفائه وإبلاغ محجر عند الحاجة.</p>
<p>لا يعد قبول حساب الفرد على المنصة تقريرًا من محجر بأن جميع صور نشاطه المستقبلية معفاة من أي متطلبات تنظيمية.</p>

<h3>المادة (7): ملكية المنتج</h3>
<p>يقر الشريك الفرد بأنه المالك المشروع للمنتج أو مخول بالتصرف فيه، وأنه لا يعلم بوجود رهن أو حجز أو بلاغ فقد أو سرقة أو حق للغير يمنع البيع أو التأجير.</p>
<p>يجوز لمحجر طلب فاتورة أو شهادة أو صور أو بيانات الرقم التسلسلي أو أي دليل مناسب على الملكية أو المصدر.</p>

<h3>المادة (8): الأصالة</h3>
<p>يلتزم الشريك بعدم عرض منتج مقلد على أنه أصلي وبصحة ما يقدمه من معلومات عن الأصالة. ويجوز لمحجر طلب فحص أو مستندات، ولا يمثل قبول الإدراج ضمان أصالة مطلقًا ما لم تقدم خدمة تحقق مستقلة وصريحة.</p>

<h3>المادة (9): ملف المنتج والرقم التسلسلي</h3>
<p>ينشأ للمنتج ملف قد يتضمن الماركة والموديل والحالة والقيمة والصور والفيديو والملحقات والرقم المرجعي أو التسلسلي ومستندات الملكية. ولا يلزم عرض الرقم التسلسلي الكامل للجمهور.</p>

<h3>المادة (10): دقة الوصف والإفصاح</h3>
<p>يلتزم الشريك بوصف حالة المنتج بصدق والإفصاح عن العيوب أو الإصلاحات أو النقص الجوهري المعروف الذي قد يؤثر على قرار العميل. ويجوز لمحجر تعليق المنتج عند وجود اختلاف جوهري أو معلومات مضللة.</p>

<h3>المادة (11): الأسعار والتوفر</h3>
<p>يحدد الشريك السعر أو يعتمد السعر المقترح وفق الخدمة. ويلتزم بتحديث توفر المنتج وعدم قبول طلب إذا أصبح غير متاح. وتظهر الأسعار والرسوم الأساسية في ملخص العملية.</p>

<h3>المادة (12): العمولات والرسوم</h3>
<p>تستحق محجر العمولة والرسوم المقررة في الجدول التجاري الساري وقت العملية. ولا تطبق رسوم غير متفق عليها أو غير مفصح عنها وفق العلاقة.</p>

<h3>المادة (13): الدفع والتسويات</h3>
<p>تتم المدفوعات من خلال الوسائل المعتمدة، وتسوى مستحقات الشريك إلى حساب مالي موثق باسمه أو معتمد وفق إجراءات محجر خلال المدة %Partner.SettlementCycle% أو حسب الجدول التجاري بعد تحقق شروط الاستحقاق.</p>
<p>يجوز تعليق الجزء محل نزاع أو استرجاع أو اعتراض دفع إلى حين تحديد أثره، دون حجز مبالغ غير مرتبطة دون مبرر.</p>

<h3>المادة (14): الضرائب والالتزامات المالية</h3>
<p>يتحمل الشريك الفرد ما ينطبق عليه نظامًا من التزامات ضريبية أو مالية بحسب صفته ونشاطه، ولا تتولى محجر تقرير وضعه الضريبي الفردي إلا في حدود ما يفرضه النظام على المنصة أو بموجب خدمة مستقلة.</p>

<h3>المادة (15): التسليم والاستلام عبر محجر</h3>
<p>في العمليات التي تتطلب تسليمًا منظمًا، يتم التسليم أو الاستلام من خلال موقع أو شريك أو آلية تعتمدها محجر. ولا يعد التسليم المباشر بين الشريك والعميل هو المسار الافتراضي للعمليات التي تشترط محجر توثيقها عبر نقطة معتمدة.</p>

<h3>المادة (16): الخصوصية وتقليل مشاركة البيانات</h3>
<p>تعمل محجر على تقليل مشاركة البيانات المباشرة بين الشريك والعميل إلى ما يلزم لتنفيذ العملية. ولا يلزم إظهار العنوان السكني أو بيانات الهوية الكاملة أو وسائل اتصال غير لازمة للطرف الآخر.</p>
<p>يعالج كل طرف البيانات التي تصله فقط للغرض المشروع، وتخضع معالجة محجر لسياسة الخصوصية ونظام حماية البيانات الشخصية.</p>

<h3>المادة (17): حماية بيانات العملاء</h3>
<p>لا يجوز للشريك استخدام بيانات العميل التي حصل عليها بسبب محجر في التسويق أو التواصل غير المرتبط بالعملية دون مسوغ مناسب، أو مشاركتها مع غير من يلزم لتنفيذ العملية.</p>

<h3>المادة (18): المحتوى وحقوق الملكية الفكرية</h3>
<p>يمنح الشريك محجر ترخيصًا محدودًا وغير حصري لاستخدام صور ووصف المنتج بالقدر اللازم للعرض والتسويق وتشغيل الخدمة. ويقر بأن المواد المقدمة منه لا تنتهك حقوق الغير.</p>

<h3>المادة (19): منع التحايل</h3>
<p>لا يجوز للشريك استخدام بيانات أو اتصال نشأ بسبب محجر لتحويل نفس العملية خارج المنصة بقصد تجنب العمولة أو إجراءات الحماية. ولا يمنع ذلك علاقة مستقلة لا تكون امتدادًا للتحايل على عملية محجر.</p>

<h3>المادة (20): السجلات الإلكترونية</h3>
<p>يجوز لمحجر حفظ سجل إلكتروني لقبول الاتفاقية وتفعيل الخدمات والطلبات والدفع والتسليم والاستلام والتقارير والمراسلات، وتستخدم هذه السجلات وفق الأنظمة ذات الصلة دون اعتبارها حجة نهائية لا تقبل المناقشة.</p>

<h3>المادة (21): الشكاوى والنزاعات</h3>
<p>يتعاون الشريك في معالجة شكاوى العملاء وتقديم المعلومات اللازمة. ويجوز لمحجر اتخاذ قرار تشغيلي مؤقت لحماية العملية أو الأموال محل النزاع، ولا يمنع ذلك الأطراف من اللجوء إلى الجهات المختصة.</p>

<h3>المادة (22): الاحتيال والمنتجات غير المشروعة</h3>
<p>يجوز لمحجر تعليق حساب أو منتج عند وجود مؤشرات جدية على تقليد أو احتيال أو تزوير أو منتج مسروق أو ملكية محل نزاع أو إساءة استخدام، وبالقدر المتناسب مع الخطر والتحقق المطلوب.</p>

<h3>المادة (23): المسؤولية</h3>
<p>يتحمل كل طرف المسؤولية عن إخلاله ضمن نطاق سيطرته وفق الأنظمة. ولا تتضمن الاتفاقية إعفاءً من مسؤولية لا يجوز نظامًا الإعفاء منها.</p>
<p>لا تضمن محجر قيمة المنتج أو تحصيلها عند الفقد أو عدم الإرجاع إلا بضمان مستقل وصريح، ولا يمثل التحقق من الهوية وحده ضمانًا ضد المخاطر.</p>

<h3>المادة (24): المطالبات الناتجة عن معلومات أو ملكية غير صحيحة</h3>
<p>يتحمل الشريك ما يثبت نظامًا من أثر مالي مباشر ناتج عن تقديم منتج لا يملكه أو عن بيان جوهري غير صحيح أو ادعاء أصالة مضلل، مع مراعاة إثبات الضرر والسبب وعدم فرض مبالغ جزافية غير مبررة.</p>

<h3>المادة (25): القوة القاهرة</h3>
<p>يعالج تعذر التنفيذ بسبب ظرف خارج عن السيطرة وفق الأنظمة، ويلتزم الطرف المتأثر بالإشعار واتخاذ ما يمكن بصورة معقولة لتقليل الضرر.</p>

<h3>المادة (26): مدة الاتفاقية والإنهاء</h3>
<p>تبدأ الاتفاقية من تاريخ القبول وتستمر حتى إنهائها. ويجوز لأي طرف إنهاؤها بإشعار %Partner.TerminationNoticeDays% يومًا، مع بقاء العمليات القائمة والحقوق والمطالبات السابقة حتى اكتمالها.</p>

<h3>المادة (27): التعليق</h3>
<p>يجوز لمحجر تعليق الحساب أو خدمة محددة عند مخالفة جوهرية أو مطالبة قائمة عالية المخاطر أو اشتباه احتيال أو عدم إرجاع أو مستندات ملكية غير كافية، مع مراجعة السبب وتمكين التصحيح عندما يكون مناسبًا.</p>

<h3>المادة (28): أثر الإنهاء</h3>
<p>لا يسقط الإنهاء مستحقات أو مسؤوليات أو عمليات بدأت قبله، وتستمر أحكام البيانات والسجلات والمطالبات والسرية بالقدر اللازم.</p>

<h3>المادة (29): التعديل والإصدارات</h3>
<p>يجوز تحديث الاتفاقية أو الملاحق مع إظهار الإصدار وتاريخ النفاذ، ولا يطبق تعديل جوهري بأثر رجعي على عملية قائمة دون أساس نظامي أو قبول مناسب.</p>

<h3>المادة (30): أولوية المستندات</h3>
<p>تكون الأولوية للأنظمة الإلزامية، ثم الشروط الخاصة بالعملية، ثم ملحق الخدمة، ثم الاتفاقية الرئيسية، ثم الجدول التجاري، ثم الإجراءات التشغيلية.</p>

<h3>المادة (31): الإشعارات</h3>
<p>ترسل الإشعارات عبر المنصة أو رقم الجوال أو البريد المسجل أو أي قناة معتمدة. ويلتزم الشريك بتحديث بيانات التواصل.</p>

<h3>المادة (32): القانون وتسوية النزاع</h3>
<p>تخضع الاتفاقية لأنظمة المملكة العربية السعودية. ويحاول الطرفان الحل الودي خلال %Partner.AmicableSettlementDays% يوم عمل من اكتمال إشعار النزاع، ثم تكون المنازعة من اختصاص الجهة القضائية المختصة في المملكة ما لم يوجد اتفاق نظامي صحيح على خلاف ذلك.</p>

<h3>المادة (33): القبول الإلكتروني</h3>
<p>يجوز قبول الاتفاقية والملاحق إلكترونيًا، ويحفظ النظام معرف المستخدم ورقم الإصدار وتاريخ ووقت القبول والخدمات المفعلة والمرجع التقني.</p>

